import { browserFixture } from "./harness.mjs";
import assert from "node:assert/strict";
import { selectRenderer } from "./renderer.mjs";
const browser = await browserFixture();
try {
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(process.env.CANVAS_URL || "http://127.0.0.1:8188");
  await selectRenderer(page);
  await page.waitForFunction(() => window.LiteGraph?.registered_node_types?.TuringMaterialText);
  const result = await page.evaluate(async () => {
    const { app } = await import("/scripts/app.js");
    const { api } = await import("/scripts/api.js");
    const workspace = await import("/extensions/comfyui-turing-utils/material_workspace.js");
    const { entries, syncPorts } = await import("/extensions/comfyui-turing-utils/lib/canvas_ports.js");
    const { snapshotCard } = await import("/extensions/comfyui-turing-utils/workspace/documents.js");
    const check = (ok, message) => { if (!ok) throw Error(message); };
    const changed = () => app.extensionManager.workflow.activeWorkflow.changeTracker.captureCanvasState();
    const wait = async (test, label) => {
      const deadline = Date.now() + 15000;
      while (Date.now() < deadline) { if (await test()) return; await new Promise((r) => setTimeout(r, 150)); }
    throw Error("Timed out: " + label + " " + app.extensionManager.workflow.activeWorkflow.turingSaveStatus);
    };
    const directory = `refinement-${Date.now()}`;
    await workspace.request("directory/create", { directory });
    await workspace.openProject(directory, true);
    const scaffold = await (await fetch("/turing/workspace/new-template")).json();
    await workspace.openTab(scaffold, "refinement.json");
    for (const node of [...app.rootGraph.nodes])
      if (node.type.startsWith("TuringMaterial") && node.type !== "TuringMaterialText") app.rootGraph.remove(node);
    const input = app.rootGraph.nodes.find((n) => n.type === "TuringCanvasInputs");
    const output = app.rootGraph.nodes.find((n) => n.type === "TuringCanvasOutputs");
    const first = app.rootGraph.nodes.find((n) => n.type === "TuringMaterialText");
    const final = LiteGraph.createNode("TuringMaterialText");
    const source = LiteGraph.createNode("PrimitiveString");
    app.rootGraph.add(final); app.rootGraph.add(source);
    source.widgets[0].value = "initial";
    input.connect(input.outputs.findIndex((s) => s._append), source, source.inputs.findIndex((s) => s.name === "value"));
    const parameter = entries(input).find((p) => p.kind === "parameter");
    check(parameter.canvas_hidden === true, "New endpoint parameters must default to hidden");
    source.connect(0, first, first.inputs.findIndex((s) => s.name === "text"));
    first.connect(0, final, final.inputs.findIndex((s) => s.name === "text"));
    input.connect(input.outputs.findIndex((s) => s._append), first, first.inputs.findIndex((s) => s.name === "position"));
    const ports = entries(input); ports.find((p) => p.kind === "position").canvas_hidden = true; syncPorts(input, ports);
    final.connect(0, output, output.inputs.findIndex((s) => s._append));
    const ids = [first, final].map((n) => n.widgets.find((w) => w.name === "stub_id").value);
    const task = await snapshotCard();
    const name = `${directory}.json`;
    await workspace.request("template/save", { name, workflow: task.workflow, prompt: task.output });
    await workspace.openProject(directory);
    const added = await workspace.addCard({ name });
    let card = app.rootGraph.nodes.find((n) => n.properties.instance === added.id);
    check(card.properties.materials.length === 2, "Unpositioned stub was not registered");
    check(card.properties.card.layout.filter((x) => x.material).length === 1, "Card must show only final preview");
    check(card.properties.card.layout.find((x) => x.material)?.material.endsWith(ids[1]), "Wrong primary preview");
    check(!card.getLayoutWidgets().some((w) => w.name === parameter.id), "Hidden parameter occupies card space");
    check(!card.getLayoutWidgets().some((w) => w._executionTarget), "Per-material generation button must default to hidden");
    await card.getExtraMenuOptions().find((m) => m.content === "隐藏参数…").callback();
    const dialog = document.querySelector("dialog[open].turing-parameter-form");
    check(dialog, "Hidden contents dialog did not open");
    check(dialog.querySelector("section textarea"), "Hidden material is absent from hidden parameters");
    const field = [...dialog.querySelectorAll("input,textarea")].find((e) => e.getAttribute("aria-label") === parameter.name);
    check(field, "Hidden input parameter is missing");
    field.value = "from-popup"; field.dispatchEvent(new Event("input", { bubbles: true }));
    [...dialog.querySelectorAll("button")].find((b) => b.textContent === "关闭").click();
    await wait(() => !dialog.isConnected, "apply hidden parameter");
    await card.getExtraMenuOptions().find((m) => m.content === "编辑工作流").callback();
    const editing = app.rootGraph.extra.turing_editor;
    check(editing?.id === added.id, "Wrong project editor");
    const endpoint = app.rootGraph.nodes.find((n) => n.type === "TuringCanvasInputs");
    const widget = endpoint.widgets.find((w) => w._portId === parameter.id && !w._valueControlTarget);
    widget.value = "autosaved"; widget.callback(widget.value); app.extensionManager.workflow.activeWorkflow.changeTracker.captureCanvasState();
    await wait(async () => (await workspace.request("card/open", { directory, id: added.id })).parameters[parameter.id] === "autosaved", "parameter autosave");
    const extra = LiteGraph.createNode("PrimitiveString"); extra.widgets[0].value = "unfinished branch"; app.rootGraph.add(extra); changed();
    await wait(async () => (await workspace.request("card/open", { directory, id: added.id })).workflow.nodes.some((n) => String(n.id) === String(extra.id)), "preserve unwired source");
    await app.queuePrompt(0, 1);
    const chosen = await workspace.request("selections", { directory });
    for (const id of ids) check(chosen.items[`${added.id}:${id}`]?.text === "autosaved", "Editor Run did not execute every stub");
    const opened = await workspace.request("card/open", { directory, id: added.id });
    check(!opened.workflow.extra.turing_card.invalid, "Valid graph saved as invalid");
    const out = app.rootGraph.nodes.find((n) => n.type === "TuringCanvasOutputs");
    app.rootGraph.remove(out); changed();
    await wait(async () => !!(await workspace.request("card/open", { directory, id: added.id })).workflow.extra.turing_card.invalid, "save incomplete graph");
    const restore = LiteGraph.createNode("TuringCanvasOutputs"); app.rootGraph.add(restore);
    await new Promise((resolve) => requestAnimationFrame(resolve));
    const end = app.rootGraph.nodes.find((n) => n.widgets?.some((w) => w.name === "stub_id" && w.value === ids[1]));
    check(end.connect(0, restore, restore.inputs.findIndex((s) => s._append)), "Cannot restore export");
    changed();
    await wait(async () => !(await workspace.request("card/open", { directory, id: added.id })).workflow.extra.turing_card.invalid, "repair saved draft");
    await app.queuePrompt(0, 2);
    const history = await (await api.fetchApi("/history")).json();
    const runs = Object.values(history).filter((r) => r.prompt[3].turing_material_run?.directory === directory);
    check(runs.length === 6, `Global Run repeated or skipped targets (${runs.length})`);
    const leaving = LiteGraph.createNode("PrimitiveString"); app.rootGraph.add(leaving); changed();
    await workspace.openProject(directory);
    check((await workspace.request("card/open", { directory, id: added.id })).workflow.nodes.some((n) => String(n.id) === String(leaving.id)), "Tab switch lost pending source changes");
    card = app.rootGraph.nodes.find((n) => n.properties.instance === added.id);
    await card.getExtraMenuOptions().find((m) => m.content === "卡片显示…").callback();
    const display = document.querySelector("dialog[open].turing-parameter-form");
    const preview = display.querySelector("select"); preview.value = "1"; preview.dispatchEvent(new Event("change"));
    display.querySelector('[role="switch"]').click();
    [...display.querySelectorAll("button")].find((b) => b.textContent === "应用").click();
    await wait(() => !display.isConnected, "save card presentation");
    check(card.properties.card.layout.filter((x) => x.material).length === 2, "Hidden positioned stub could not be shown from card settings: " + JSON.stringify({ layout: card.properties.card.layout, remote: (await workspace.request("project/open", { directory })).document.cards[0].layout }));
    check(card.widgets.some((w) => w.name === parameter.id), "Pinned parameter is missing");
    return { directory, hiddenMaterials: true, optionalPosition: true, editorRun: true, autosave: true, incompleteDraft: true, batches: true, tabFlush: true, presentation: true };
  });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ renderer: process.env.NODES_MODE || "classic", ...result }));
} finally { await browser.close(); }
