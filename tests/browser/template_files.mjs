import { browserFixture } from "./harness.mjs";
import assert from "node:assert/strict";
import { selectRenderer } from "./renderer.mjs";

const browser = await browserFixture();
try {
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(process.env.CANVAS_URL || "http://127.0.0.1:8188");
  await selectRenderer(page);
  const state = await page.evaluate(async () => {
    const workspace = await import("/extensions/comfyui-turing-utils/material_workspace.js");
    const { documentPath } = await import("/extensions/comfyui-turing-utils/workspace/documents.js");
    const { api } = await import("/scripts/api.js");
    const check = (ok, message) => { if (!ok) throw Error(message); };
    const pause = () => new Promise((resolve) => setTimeout(resolve, 50));
    const until = async (predicate, label) => {
      for (let i = 0; i < 120; i++) { if (await predicate()) return; await pause(); }
      throw Error("Timed out: " + label);
    };
    const command = (id) => app.extensionManager.command.execute(id);
    const prefix = `template-files-${Date.now()}`;
    const prompt = app.extensionManager.dialog.prompt;
    const read = (name) => workspace.request("template/open", { name });
    const value = (file, id) => file.workflow.nodes.find((n) => String(n.id) === String(id)).widgets_values[0];
    const make = async (suffix) => {
      await command("Turing.MaterialWorkspace.New");
      const node = LiteGraph.createNode("PrimitiveString");
      app.rootGraph.add(node); node.widgets[0].value = suffix;
      const text = app.rootGraph.nodes.find((n) => n.type === "TuringMaterialText");
      node.connect(0, text, text.inputs.findIndex((s) => s.name === "text"));
      const seed = LiteGraph.createNode("PrimitiveInt");
      app.rootGraph.add(seed); app.rootGraph.convertToSubgraph(new Set([seed]));
      const name = `${prefix}-${suffix}.json`;
      app.extensionManager.dialog.prompt = async () => name;
      const tab = app.extensionManager.workflow.activeWorkflow;
      await new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));
      await tab.save();
      return { tab, name, id: node.id };
    };
    const b = await make("B"), a = await make("A");
    const edit = (id, text) => {
      app.rootGraph.getNodeById(id).widgets[0].value = text;
      app.rootGraph.change();
      app.extensionManager.workflow.activeWorkflow.changeTracker.captureCanvasState();
    };
    edit(a.id, "before rename");
    const renamed = `${prefix}-renamed.json`;
    await app.extensionManager.workflow.renameWorkflow(a.tab, documentPath({ name: renamed }));
    check(!(await workspace.request("templates")).items.includes(a.name), "Rename left the original file behind");
    check(value(await read(renamed), a.id) === "before rename", "Rename lost a pending edit");
    check(app.rootGraph.extra.turing_editor.name === renamed && a.tab.path === documentPath({ name: renamed }), "Rename did not update the tab's file identity");
    await command("Comfy.Undo");
    await a.tab.save({ automatic: true, settle: true });
    check(app.rootGraph.extra.turing_editor.name === renamed, "Undo restored a template's old filename");
    const nativeFetch = api.fetchApi;
    let enter, release;
    const entered = new Promise((resolve) => { enter = resolve; });
    const blocked = new Promise((resolve) => { release = resolve; });
    api.fetchApi = async function (path, ...args) {
      const response = await nativeFetch.call(this, path, ...args);
      if (path.endsWith("/template/rename")) { enter(); await blocked; }
      return response;
    };
    const finalName = `${prefix}-final.json`;
    const renaming = app.extensionManager.workflow.renameWorkflow(a.tab, documentPath({ name: finalName }));
    await entered;
    edit(a.id, "during rename");
    const saving = a.tab.save({ automatic: true, settle: true });
    release(); await Promise.all([renaming, saving]);
    api.fetchApi = nativeFetch;
    check(value(await read(finalName), a.id) === "during rename", "A save racing with Rename wrote the wrong file");
    check(!(await workspace.request("templates")).items.includes(renamed), "A late save recreated the pre-rename file");
    const conflict = await app.extensionManager.workflow.renameWorkflow(a.tab, documentPath({ name: b.name })).then(() => false, (error) => error.message.includes("already exists"));
    check(conflict && a.tab.path === documentPath({ name: finalName }) && value(await read(b.name), b.id) === "B", "Rename overwrote another template or changed identity on failure");
    await app.loadGraphData(JSON.parse(JSON.stringify(b.tab.activeState)), true, true, b.tab);
    const copyName = `${prefix}-inactive-copy.json`;
    await a.tab.saveAs(documentPath({ name: copyName }));
    check(app.rootGraph.extra.turing_editor.name === copyName && value(await read(copyName), a.id) === "during rename", "Save As copied the active tab instead of its source");
    check(value(await read(b.name), b.id) === "B", "Inactive Save As changed the previously active template: " + value(await read(b.name), b.id));
    check((await read(copyName)).workflow.definitions.subgraphs.length === 1, "Save As lost a native subgraph");
    edit(a.id, "independent copy");
    await app.extensionManager.workflow.activeWorkflow.save({ automatic: true, settle: true });
    check(value(await read(finalName), a.id) === "during rename", "Editing the copy modified its source");
    check(value(await read(b.name), b.id) === "B", "Saving the copy changed the other template: " + value(await read(b.name), b.id));
    app.extensionManager.dialog.prompt = async () => b.name;
    const currentTab = app.extensionManager.workflow.activeWorkflow;
    await command("Comfy.SaveWorkflowAs");
    check(app.extensionManager.workflow.activeWorkflow === currentTab, "Save As accepted an occupied filename");
    check(value(await read(b.name), b.id) === "B", "Save As overwrote an occupied filename: " + value(await read(b.name), b.id));
    const external = await read(copyName);
    external.workflow.nodes.find((n) => String(n.id) === String(a.id)).title = "External copy version";
    await workspace.request("template/save", { name: copyName, revision: external.revision, workflow: external.workflow, prompt: external.workflow.extra.turing_card.prompt });
    const conflictedTab = app.extensionManager.workflow.activeWorkflow;
    edit(a.id, "rescued local draft");
    check(await conflictedTab.save().then(() => false, (error) => error.message.includes("changed")), "The external-conflict fixture did not reject Save");
    const rescueName = `${prefix}-rescued.json`;
    await conflictedTab.saveAs(documentPath({ name: rescueName }));
    check(value(await read(rescueName), a.id) === "rescued local draft" && conflictedTab.isModified, "Save As could not rescue a conflicting draft");
    check(value(await read(copyName), a.id) === "independent copy", "Rescuing a draft overwrote the external file");
    await app.extensionManager.workflow.closeWorkflow(a.tab);
    const sidebar = app.extensionManager.getSidebarTabs().find((tab) => tab.id === "turing.canvas");
    const host = document.createElement("div"); document.body.append(host); sidebar.render(host);
    const filter = host.querySelector("input"); filter.value = prefix; filter.dispatchEvent(new Event("input"));
    const row = (name) => [...host.querySelectorAll("button")].find((button) => button.textContent === name);
    await until(() => row(finalName), "sidebar library");
    const menu = async (name, label, destination) => {
      app.extensionManager.dialog.prompt = async () => destination;
      row(name).dispatchEvent(new MouseEvent("contextmenu", { bubbles: true, clientX: 200, clientY: 180, cancelable: true }));
      const option = [...document.querySelectorAll(".litecontextmenu .litemenu-entry")].find((element) => element.textContent === label);
      check(option, "Missing sidebar action: " + label); option.click();
    };
    const sidebarName = `${prefix}-sidebar`;
    await menu(finalName, "重命名…", sidebarName);
    await until(() => row(sidebarName + ".json"), "sidebar rename");
    const sidebarCopy = `${prefix}-sidebar-copy`;
    await menu(sidebarName + ".json", "复制卡片模板…", sidebarCopy);
    await until(() => app.rootGraph.extra.turing_editor?.name === sidebarCopy + ".json", "sidebar copy");
    check(value(await read(sidebarCopy + ".json"), a.id) === "during rename", "Sidebar copy lost its source values");
    check((await read(sidebarName + ".json")).workflow.id !== app.rootGraph.id, "Sidebar copy reused its source graph identity");
    sidebar.destroy(); host.remove();
    app.rootGraph.remove(app.rootGraph.nodes.find((node) => node.type === "TuringCanvasOutputs"));
    await app.extensionManager.workflow.activeWorkflow.save({ automatic: true, settle: true });
    const draftCopy = `${prefix}-unfinished.json`;
    app.extensionManager.dialog.prompt = async () => draftCopy;
    await command("Comfy.SaveWorkflowAs");
    check((await read(draftCopy)).workflow.extra.turing_card.invalid, "Save As could not preserve an unfinished template");
    await app.loadGraphData(JSON.parse(JSON.stringify(b.tab.activeState)), true, true, b.tab);
    app.extensionManager.dialog.prompt = async () => `${prefix}-tab-renamed`;
    window.templateFilesFixture = { prefix, b, check, read, value, edit, prompt, until };
    return { prefix, original: b.name, path: b.tab.path };
  });
  await page.waitForTimeout(250);
  const sourceTab = () => page.locator(`[data-workflow-path="${state.path}"]`);
  await sourceTab().dispatchEvent("contextmenu", { bubbles: true, cancelable: true, button: 2, clientX: 200, clientY: 80 });
  await page.getByRole("menuitem", { name: /Rename|重命名/ }).first().dispatchEvent("click");
  await page.waitForFunction(() => app.rootGraph.extra.turing_editor?.name.endsWith("-tab-renamed.json"));
  const renamedPath = await page.evaluate(() => app.extensionManager.workflow.activeWorkflow.path);
  await page.locator(`[data-workflow-path="${renamedPath}"]`).dispatchEvent("contextmenu", { bubbles: true, cancelable: true, button: 2, clientX: 200, clientY: 80 });
  await page.getByRole("menuitem", { name: /Duplicate|复制/ }).first().dispatchEvent("click");
  await page.waitForFunction(() => {
    const store = app.extensionManager.workflow, tab = store.activeWorkflow;
    const draft = app.rootGraph.extra.turing_editor?.new;
    return draft && tab?.activeState?.extra?.turing_editor?.new === draft && tab.path.startsWith("workflows/canvas/new/") && !store.isBusy;
  });
  const result = await page.evaluate(async () => {
    const { prefix, b, check, read, value, edit, prompt } = window.templateFilesFixture;
    const originalName = prefix + "-tab-renamed.json";
    check(app.extensionManager.workflow.activeWorkflow !== b.tab, "Native Duplicate reopened the source tab");
    check(app.rootGraph.extra.turing_editor.source === originalName && !app.rootGraph.extra.turing_editor.name, "Native Duplicate retained the original template identity");
    check(app.rootGraph.getNodeById(b.id).widgets[0].value === "B", "Native Duplicate used another tab's graph");
    edit(b.id, "native copy");
    app.extensionManager.dialog.prompt = async () => prefix + "-native-copy";
    await app.extensionManager.command.execute("Comfy.RenameWorkflow");
    check(value(await read(originalName), b.id) === "B", "Saving a native duplicate overwrote the original");
    check(value(await read(prefix + "-native-copy.json"), b.id) === "native copy", "Native duplicate was not saved in the card library");
    app.extensionManager.dialog.prompt = prompt;
    return { mode: LiteGraph.vueNodesMode ? "vue" : "classic", rename: true, renameDuringSave: true, conflicts: true, inactiveSaveAs: true, sidebarRename: true, sidebarCopy: true, unfinishedSaveAs: true, nativeRename: true, nativeDuplicate: true };
  });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify(result));
} finally {
  await browser.close();
}
